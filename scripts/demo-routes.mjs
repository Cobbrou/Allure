// Regenerates src/lib/demoRoutes.js: real loops following OSM paths and roads, so demo
// activities line up with the map. Run with `node scripts/demo-routes.mjs` (needs network).
// Routing: FOSSGIS OSRM (routing.openstreetmap.de), © OpenStreetMap contributors (ODbL).

import { writeFileSync } from 'node:fs';

// Waypoints [lon, lat], visited in order and back to the first.
const LOOPS = {
  Chamonix: {
    foot: [[6.8694, 45.9237], [6.8920, 45.9395], [6.8810, 45.9330]],
    bike: [[6.8694, 45.9237], [6.9280, 45.9800], [6.9000, 45.9550]],
  },
  Annecy: {
    foot: [[6.1290, 45.8990], [6.1440, 45.9045], [6.1360, 45.9060]],
    bike: [[6.1290, 45.8990], [6.1410, 45.8640], [6.1300, 45.8850]],
  },
  Paris: {
    foot: [[2.3522, 48.8566], [2.2945, 48.8584], [2.3130, 48.8630]],
    bike: [[2.2490, 48.8620], [2.2600, 48.8530], [2.2380, 48.8700]],
  },
};

async function route(profile, waypoints) {
  const coords = [...waypoints, waypoints[0]].map((c) => c.join(',')).join(';');
  const url = `https://routing.openstreetmap.de/routed-${profile}/route/v1/driving/${coords}?overview=full&geometries=geojson`;
  const res = await fetch(url, { headers: { 'User-Agent': 'allure-dev-demo-routes' } });
  const json = await res.json();
  if (json.code !== 'Ok') throw new Error(`${profile} ${url}: ${json.code} ${json.message ?? ''}`);
  const r = json.routes[0];
  console.log(`${profile}: ${(r.distance / 1000).toFixed(1)} km, ${r.geometry.coordinates.length} points`);
  return r.geometry.coordinates.map(([lon, lat]) => [Math.round(lon * 1e5) / 1e5, Math.round(lat * 1e5) / 1e5]);
}

const out = {};
for (const [place, loops] of Object.entries(LOOPS)) {
  out[place] = {};
  for (const [profile, wps] of Object.entries(loops)) {
    process.stdout.write(`${place} `);
    out[place][profile] = await route(profile, wps);
    await new Promise((r) => setTimeout(r, 1000)); // be gentle with the public server
  }
}

writeFileSync(new URL('../src/lib/demoRoutes.js', import.meta.url),
  `// Generated by scripts/demo-routes.mjs. Do not edit. Route data © OpenStreetMap contributors (ODbL).\n` +
  `// Closed loops of [lon, lat], per place and profile (foot, bike).\n` +
  `export const DEMO_ROUTES = ${JSON.stringify(out)};\n`);
